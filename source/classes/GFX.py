class GFXData:
    BANK_POINTER = 0x00CFC0
    PAGE_POINTER = 0x00D09F
    DATA_POINTER = 0x00D17E

    OVERFLOW_ADDRESS = 0xA59000

    def __init__(self, index: int, address: int, size: int):
        self.index = index
        self.address = address
        self.size = size
        self.shared_gfx = None
        self.stored_uncompressed = False
        self.file_replacement = None

    def shared(self, shared_idx: int):
        self.shared_gfx = shared_idx
        return self

    def uncompressed(self):
        self.stored_uncompressed = True
        return self

    def replacement(self, file_path: str):
        self.file_replacement = file_path

